import { test, expect } from '@playwright/test';

test('B1 exam: answer reading, listen externally and preserve selections', async ({ page }) => {
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.setViewportSize({ width: 360, height: 800 });
  await page.goto('/');
  await page.getByLabel('Email', { exact: true }).fill(process.env.VERIFY_EMAIL);
  await page.getByLabel('Mật khẩu', { exact: true }).fill(process.env.VERIFY_PASSWORD);
  await page.getByRole('button', { name: 'Vào góc học của tôi' }).click();
  await page.getByRole('button', { name: 'Bắt đầu', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Kết thúc phiên' })).toBeVisible();
  await page.getByRole('link', { name: 'Bộ đề B1' }).click();
  await expect(page.getByRole('heading', { name: 'Bộ đề tiếng Anh B1', exact: true })).toBeVisible();
  await expect(page.locator('.b1-session-note').first()).toContainText('Không giới hạn thời gian');
  await expect(page.getByRole('button', { name: 'Bắt đầu', exact: true })).toHaveCount(0);
  let firstQuestion = page.locator('.b1-question').first();
  await firstQuestion.getByRole('radio').first().check();
  await expect(page.getByRole('status').filter({ hasText: 'Đã lưu bài làm' })).toBeVisible();
  await page.reload();
  firstQuestion = page.locator('.b1-question').first();
  await expect(firstQuestion.getByRole('radio').first()).toBeChecked();
  await firstQuestion.getByRole('button', { name: 'Xem đáp án' }).click();
  await expect(firstQuestion.getByRole('region', { name: 'Đáp án' })).toContainText('Giải thích');
  await expect(firstQuestion.getByRole('region', { name: 'Đáp án' })).toContainText('Bản dịch');
  await page.getByRole('button', { name: /Đề mẫu · Nghe/ }).click();
  const listen = page.locator('.b1-question').first();
  await expect(listen.locator('img')).toBeVisible();
  await expect(listen.locator('img')).toHaveJSProperty('naturalWidth', await listen.locator('img').evaluate((image) => image.naturalWidth));
  expect(await listen.locator('img').evaluate((image) => image.naturalWidth)).toBeGreaterThan(0);
  await expect(listen.getByRole('button', { name: 'Xem đáp án' })).toHaveCount(0);
  await listen.getByRole('radio').first().check();
  await expect(page.getByRole('status').filter({ hasText: 'Đã lưu bài làm' })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: /Đề mẫu · Nghe/ }).click();
  await expect(page.locator('.b1-question').first().getByRole('radio').first()).toBeChecked();
  await page.getByRole('button', { name: /Đề mẫu · Đọc hiểu/ }).click();
  await expect(page.locator('.b1-question').first().getByRole('radio').first()).toBeChecked();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  await page.getByRole('link', { name: 'Hôm nay', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Kết thúc phiên' })).toBeVisible();
  expect(errors).toEqual([]);
});
